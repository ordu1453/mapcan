def fmt_num(x: float) -> str:
    if x == int(x):
        return str(int(x))
    return f"{x:.10g}"


def fmt_value(v: int, s: Signal) -> str:
    if s.value_format == "hex" and v >= 0:
        return f"0x{v:0{max(2, (s.bit_length + 3) // 4)}X}"
    return str(v)


def hex_id(can_id: int | None, extended: bool = False) -> str:
    if can_id is None:
        return "—"
    return f"0x{can_id:08X}" if extended else f"0x{can_id:03X}"


def _range(a: int, b: int, sep: str = "–") -> str:
    return str(a) if a == b else f"{a}{sep}{b}"


class ViewBuilder:
    def __init__(self, cmap: MapCan, lang: str | None = None):
        self.cmap = cmap
        self.lang = lang or cmap.lang
        self.L = LABELS.get(self.lang, LABELS["ru"])

    def t(self, value) -> str:
        return text(value, self.lang)

    def unit(self, value: str | None) -> str:
        """Единица на языке документа (из справочника units) или как записана; None → ""."""
        return translate_unit(value, self.lang) or ""

    # ------------------------------------------------------------------ #

    def build(self) -> dict:
        d = self.cmap.document
        date = d.date or _dt.date.today()
        sig = d.signatures
        logo = self.cmap.logo_path
        buses = [self.bus(b) for b in self.cmap.buses]
        return {
            "lang": self.lang,
            "labels": self.L,
            "document": {
                "title": self.t(d.title),
                "subtitle": self.t(d.subtitle),
                "version": d.version,
                "date": date.isoformat(),
                "date_ru": date.strftime("%d.%m.%Y"),
                "year": str(date.year),
                "author": d.author or "",
                "organization": d.organization or "",
                "designation": d.designation or "",
                "litera": d.litera or "",
                "city": d.city or "",
                # Путь логотипа для шаблона выставляет экспортёр (logo); logo_file — исходный файл.
                "logo": "",
                "logo_file": str(logo) if logo and logo.is_file() else "",
                "signatures": {
                    k: (getattr(sig, k) or "") if sig else ""
                    for k in ("developed", "checked", "tech_control", "norm_control", "approved")
                },
                "approve": {"position": d.approve.position or "", "name": d.approve.name} if d.approve else None,
                "agree": [{"position": p.position or "", "name": p.name} for p in d.agree],
                "stats": {
                    "buses": len(buses),
                    "devices": sum(b["stats"]["devices"] for b in buses),
                    "frames": sum(b["stats"]["frames"] for b in buses),
                    "signals": sum(b["stats"]["signals"] for b in buses),
                },
                "bit_note": self.L["bit_note"],
                "history": [
                    {"version": h.version, "date": h.date.isoformat() if h.date else "",
                     "author": h.author or "",
                     "github": h.github or "",
                     "github_url": f"https://github.com/{h.github}" if h.github else "",
                     "author_label": " ".join(x for x in (h.author or "", f"@{h.github}" if h.github else "") if x),
                     "changes": [self.t(c) for c in h.changes]}
                    for h in d.history
                ],
            },
            "buses": buses,
            "palette": PALETTE,
            "empty_color": EMPTY_COLOR,
        }

    def bus(self, bus) -> dict:
        devices = [self.device(dv) for dv in bus.devices]
        broadcast = [self.frame(f) for f in bus.frames]
        nframes = len(bus.all_frames())
        nsignals = sum(len(f.layout) for f in bus.all_frames())
        return {
            "name": bus.name,
            "title": self.t(bus.title) or bus.name,
            "interface": bus.interface or "",
            "bitrate": f"{bus.bitrate // 1000} кбит/с" if bus.bitrate and self.lang == "ru"
                       else (f"{bus.bitrate // 1000} kbit/s" if bus.bitrate else ""),
            "protocol": {"canopen": "CANopen", "j1939": "SAE J1939"}.get(bus.protocol, "CAN FD" if bus.fd else "CAN"),
            "description": self.t(bus.description),
            "devices": devices,
            "broadcast": broadcast,
            "addressing": self.addressing(bus),
            "stats": {"frames": nframes, "signals": nsignals, "devices": len(bus.devices)},
        }

    def device_label(self, dev) -> str:
        short = dev.short or dev.name.upper()
        if dev.node_id is not None:
            return f"{short} 0x{dev.node_id:02X}"
        if dev.address is not None:
            return f"{short} SA 0x{dev.address:02X}"
        return short

    def device(self, dev) -> dict:
        return {
            "name": dev.name,
            "short": dev.short or dev.name.upper(),
            "label": self.device_label(dev),
            "title": self.t(dev.title),
            "node_id": f"0x{dev.node_id:02X}" if dev.node_id is not None else "",
            "description": self.t(dev.description),
            "frames": [self.frame(f) for f in dev.frames],
        }

    # ------------------------------------------------------------------ #

    def addressing(self, bus) -> dict:
        L = self.L
        if bus.protocol == "canopen":
            columns = [self.device_label(dv) for dv in bus.devices]
            rows = []
            for ftype in ADDRESSING_ORDER:
                fc = FUNCTION_CODES[ftype]
                bc = [f for f in bus.frames if f.type == ftype]
                cells = []
                for dv in bus.devices:
                    fr = [f for f in dv.frames if f.type == ftype]
                    cells.append([self._addr_cell(f) for f in fr])
                rows.append({
                    "type": ftype,
                    "label": fc.label_ru if self.lang == "ru" else fc.label_en,
                    "base": f"0x{fc.base:03X}",
                    "purpose": fc.purpose_ru if self.lang == "ru" else fc.purpose_en,
                    "broadcast": [self._addr_cell(f) for f in bc],
                    "cells": cells,
                    "used": bool(bc) or any(cells),
                })
            # Кадры типа raw на шине CANopen — отдельной строкой.
            raw_cells = [[self._addr_cell(f) for f in dv.frames if f.type == "raw"] for dv in bus.devices]
            raw_bc = [self._addr_cell(f) for f in bus.frames if f.type == "raw"]
            if any(raw_cells) or raw_bc:
                rows.append({"type": "raw", "label": "RAW", "base": "", "purpose": "",
                             "broadcast": raw_bc, "cells": raw_cells, "used": True})
            return {"kind": "matrix", "columns": columns, "rows": rows,
                    "broadcast_label": L["broadcast"]}
        rows = []
        for f in sorted(bus.all_frames(), key=lambda f: (f.can_id is None, f.can_id or 0)):
            rows.append({"device": self.device_label(f.device) if f.device else L["broadcast"],
                         **self._addr_cell(f)})
        return {"kind": "list", "rows": rows,
                "has_pgn": any(r["pgn"] for r in rows), "has_receivers": any(r["receivers"] for r in rows)}

    def _addr_cell(self, f: Frame) -> dict:
        return {"id": hex_id(f.can_id, f.extended), "name": f.name,
                "description": self.t(f.description) or self.t(f.title),
                "direction": f.direction.upper() if f.direction else "",
                "period": self.mode_label(f),
                "pgn": f"0x{f.pgn:04X}" if f.pgn is not None else "",
                "receivers": self.receivers(f)}

    def raw_type(self, f: Frame) -> str:
        """Тип кадра без функционального кода CANopen: J1939 PDU1/PDU2, CAN 11/29 бит, CAN FD."""
        if f.bus.protocol == "j1939" and f.pgn is not None:
            return "J1939 PDU1" if j1939_is_pdu1(f.pgn) else "J1939 PDU2"
        bits = ("29" if f.extended else "11") + (" бит" if self.lang == "ru" else "-bit")
        return f"CAN FD {bits}" if f.bus.fd and f.dlc > 8 else f"CAN {bits}"

    def receivers(self, f: Frame) -> str:
        names = {d.name: self.device_label(d) for d in f.bus.devices}
        return ", ".join(names.get(r, r) for r in f.receivers)

    def mode_label(self, f: Frame) -> str:
        tr = f.transmission
        if tr is None:
            return ""
        if tr.mode == "cyclic":
            return self.L["cyclic"].format(ms=tr.cycle_ms or "?")
        return self.L[tr.mode]

    # ------------------------------------------------------------------ #

    def frame(self, f: Frame) -> dict:
        sigs = f.layout
        colors = {i: PALETTE[i % len(PALETTE)] for i in range(len(sigs))}
        fc = FUNCTION_CODES.get(f.type)
        formula = ""
        if fc and fc.per_node and f.device is not None and f.id is None and f.bus.protocol == "canopen":
            formula = f"0x{fc.base:03X} + node_id"
        selector = next((s for s in sigs if s.multiplexer), None)
        return {
            "name": f.name,
            "title": self.t(f.title),
            "description": self.t(f.description),
            "type": f.type,
            "type_label": (fc.label_ru if self.lang == "ru" else fc.label_en) if fc else self.raw_type(f),
            "id": hex_id(f.can_id, f.extended),
            "id_formula": formula,
            "dlc": f.dlc,
            "direction": (f.direction or "").upper(),
            "period": self.mode_label(f),
            "pgn": f"0x{f.pgn:04X}" if f.pgn is not None else "",
            "priority": "" if f.bus.protocol != "j1939" else str(6 if f.priority is None else f.priority),
            "receivers": self.receivers(f),
            "comment": self.t(f.comment),
            "signals": [self.signal(s, colors[i], selector) for i, s in enumerate(sigs)],
            "grid": self.grid(f, sigs, colors),
            "sdo": [self.sdo(e) for e in f.sdo or []],
        }

    def sdo(self, e) -> dict:
        v = e.value
        return {
            "name": e.name,
            "description": self.t(e.description),
            "command": f"0x{e.command:02X}",
            "index": f"0x{e.index:04X}",
            "subindex": f"0x{e.subindex:02X}",
            "value": (f"{v.name}: {v.bit_length} {self.L['bits'].lower()}"
                      + (f", {fmt_num(v.factor)} {self.unit(v.unit)}{self.L['per_bit']}" if v.unit else "")
                      ) if v else "—",
        }

    def signal(self, s: Signal, color: str, selector: Signal | None) -> dict:
        L = self.L
        be = s.byte_order == "big_endian"
        b0, b1 = B.byte_span(s.start_bit, s.bit_length, be)
        occ = B.occupied_bits(s.start_bit, s.bit_length, be)
        lo, hi = min(occ), max(occ)
        whole_bytes = s.start_bit % 8 == 0 and s.bit_length % 8 == 0
        bytes_label = _range(b0, b1)
        bits_label = _range(lo, hi)

        enc = []
        if s.kind in ("enum", "raw", "metric", "flag") or s.kind is None:
            if s.bit_length in (8, 16, 32, 64) and whole_bytes:
                enc.append(("int" if s.signed else "uint") + str(s.bit_length))
            else:
                enc.append(f"{s.bit_length} {L['bit']}")
                if s.signed:
                    enc[-1] += f", {L['signed']}"
            if s.signed and s.signed_code in ("ones_complement", "sign_magnitude"):
                enc[-1] += f", {L[s.signed_code]}"
        elif s.kind == "float":
            enc.append(f"float{s.bit_length}" if s.bit_length in (32, 64) else f"{s.bit_length} {L['bit']}")
        elif s.kind == "bitfield":
            enc.append(L["bitfield"])
        elif s.kind == "bytes":
            enc.append(f"{s.bit_length // 8} {L['bytes']}" if whole_bytes else f"{s.bit_length} {L['bit']}")
        unit = self.unit(s.unit)
        if s.kind == "metric" or s.factor != 1 or s.offset != 0:
            enc.append(f"{fmt_num(s.factor)} {unit}{L['per_bit']}".replace(" /", "/"))
            if s.offset:
                enc.append(f"{L['offset']} {fmt_num(s.offset)} {unit}".strip())
        elif unit:
            enc.append(unit)
        if b1 > b0 and s.kind != "bytes":
            enc.append(L[s.byte_order])
        if s.multiplexer:
            enc.append(L["selector"])

        values = []
        for v, ev in enum_entries(s.values):
            d = self.t(ev.description)
            values.append(f"{fmt_value(v, s)} – {ev.name}" + (f" ({d})" if d else ""))
        for fl in s.flags or []:
            d = self.t(fl.description)
            pos = _range(fl.bit, fl.bit + fl.bit_length - 1)
            line = f"{L['bit']} {pos} – {fl.name.upper()}" + (f" ({d})" if d else "")
            sub = [f"{v}={ev.name}" for v, ev in enum_entries(fl.values)]
            if sub:
                line += " [" + ", ".join(sub) + "]"
            values.append(line)
        if s.min is not None or s.max is not None:
            mn = fmt_num(s.min) if s.min is not None else "…"
            mx = fmt_num(s.max) if s.max is not None else "…"
            values.append(f"{L['range']}: {mn} … {mx} {unit}".rstrip())
        if s.initial is not None:
            values.append(f"{L['initial']}: {fmt_num(s.initial)} {unit}".rstrip())
        if s.invalid_values:
            values.append(f"{L['invalid']}: " + ", ".join(fmt_value(v, s) if s.value_format == "hex"
                                                         else f"0x{v:X}" if v >= 0 else str(v)
                                                         for v in s.invalid_values))

        mux = ""
        if s.mux is not None and selector is not None:
            names = dict(enum_entries(selector.values))
            vals = ", ".join(fmt_value(v, selector) + (f" ({names[v].name})" if v in names else "")
                             for v in s.mux_values)
            mux = L["when"].format(sel=selector.name, vals=vals)

        return {
            "name": s.name,
            "upper": s.name.upper(),
            "description": self.t(s.description),
            "kind": s.kind,
            "kind_label": L.get(s.kind, s.kind),
            "start_bit": s.start_bit,
            "bit_length": s.bit_length,
            "bytes": bytes_label,
            "bits": bits_label,
            "byte_first": b0,
            "byte_last": b1,
            "encoding": enc,
            "values": values,
            "mux": mux,
            "comment": self.t(s.comment),
            "color": color,
        }

    def grid(self, f: Frame, sigs: list[Signal], colors: dict) -> list[dict]:
        """Строки битовой диаграммы: на каждый байт — сегменты слева направо (бит 7 → 0)."""
        owner: dict[int, list[int]] = {}
        flag_at: dict[int, str] = {}   # абсолютный бит → имя флага битового поля
        for i, s in enumerate(sigs):
            occ = B.occupied_bits(s.start_bit, s.bit_length, s.byte_order == "big_endian")
            for b in occ:
                owner.setdefault(b, []).append(i)
            for fl in s.flags or []:
                for k in range(fl.bit, min(fl.bit + fl.bit_length, len(occ))):
                    flag_at[occ[k]] = fl.name
        rows = []
        for byte in range(f.dlc):
            cells = []
            for bit in range(7, -1, -1):
                p = byte * 8 + bit
                key = tuple(owner.get(p, []))
                label = flag_at.get(p) if len(key) == 1 else None
                cells.append((key, label))
            segs = []
            col = 0
            while col < 8:
                key, flag = cells[col]
                span = 1
                while col + span < 8 and cells[col + span] == (key, flag):
                    span += 1
                if key:
                    label = flag or " | ".join(sigs[i].name for i in key)
                    color = colors[key[0]]
                    hi_bit = byte * 8 + 7 - col
                    lo_bit = hi_bit - span + 1
                else:
                    label, color, lo_bit, hi_bit = "", EMPTY_COLOR, None, None
                segs.append({"col": col, "span": span, "label": label, "color": color,
                             "signals": list(key), "conflict": _conflict(sigs, key),
                             "lo": lo_bit, "hi": hi_bit})
                col += span
            rows.append({"byte": byte, "segments": segs,
                         "cells": [{"bit": byte * 8 + 7 - c, "signals": list(cells[c][0])} for c in range(8)]})
        return rows


def _conflict(sigs: list[Signal], key: tuple) -> bool:
    """Есть ли среди сигналов бита пара, присутствующая в кадре одновременно."""
    for a in range(len(key)):
        for b in range(a):
            ma, mb = sigs[key[a]].mux_values, sigs[key[b]].mux_values
            if ma is None or mb is None or set(ma) & set(mb):
                return True
    return False


def build_view(cmap: MapCan, lang: str | None = None) -> dict:
    return ViewBuilder(cmap, lang).build()
