"""EDS (CiA 306) of a CANopen device: the dictionary objects mapped into its PDOs, and the PDO parameters.

One file per device of a CANopen bus. The dictionary has the mandatory objects (1000, 1001, 1018),
the producer heartbeat (1017, if the device has a heartbeat frame), the communication and mapping
parameters of each PDO that has signals with an ``index`` (1400/1600: RPDO, 1800/1A00: TPDO), and the
signal objects themselves. Gaps between the signals of a PDO are filled with dummy objects (0x0001, 0x0005).
"""

from __future__ import annotations

import datetime as _dt
from collections.abc import Callable
from pathlib import Path

from .. import __version__
from ..canopen import FUNCTION_CODES
from ..i18n import _
from ..model import Bus, Device, Frame, MapCan, Signal, text

BOOLEAN, UNSIGNED8, VISIBLE_STRING, OCTET_STRING = 0x0001, 0x0005, 0x0009, 0x000A
UNSIGNED = {8: 0x0005, 16: 0x0006, 24: 0x0016, 32: 0x0007, 40: 0x0018, 48: 0x0019, 56: 0x001A, 64: 0x001B}
INTEGER = {8: 0x0002, 16: 0x0003, 24: 0x0010, 32: 0x0004, 40: 0x0012, 48: 0x0013, 56: 0x0014, 64: 0x0015}
REAL = {32: 0x0008, 64: 0x0011}
BAUD_RATES = (10, 20, 50, 125, 250, 500, 800, 1000)


def data_type(s: Signal) -> int:
    """CiA 301 data type of a signal: the smallest standard one that holds its bits."""
    if s.is_float:
        return REAL[64 if s.bit_length > 32 else 32]
    if s.encoding == "bytes":
        return VISIBLE_STRING if s.is_text else OCTET_STRING
    if s.bit_length == 1 and not s.signed:
        return BOOLEAN
    size = next(n for n in sorted(UNSIGNED) if n >= s.bit_length)
    return (INTEGER if s.signed else UNSIGNED)[size]


def pdo_number(frame: Frame) -> int:
    return int(frame.type[-1])


def _mapping(frame: Frame, warn) -> list[tuple[int, int, int]] | None:
    """PDO mapping: (index, subindex, length in bits) in bit order, with dummy objects in the gaps."""
    mapped = sorted((s for s in frame.signals if s.index is not None), key=lambda s: s.start_bit)
    if not mapped:
        return None
    if any(s.mux is not None or s.holds_selector for s in frame.signals):
        warn(_("{frame}: a multiplexed PDO is not mapped in the EDS", frame=frame.name))
        return None
    out, pos = [], 0
    for s in mapped:
        if s.start_bit < pos:
            warn(_("{frame}.{signal}: overlaps the previous object and is not mapped in the EDS",
                   frame=frame.name, signal=s.name))
            continue
        while pos < s.start_bit:          # gap: dummy UNSIGNED8 per byte, BOOLEAN per bit
            if pos % 8 == 0 and s.start_bit - pos >= 8:
                out.append((UNSIGNED8, 0, 8))
                pos += 8
            else:
                out.append((BOOLEAN, 0, 1))
                pos += 1
        out.append((s.index, s.subindex or 0, s.bit_length))
        pos = s.start_bit + s.bit_length
    return out


class _Writer:
    def __init__(self):
        self.lines: list[str] = []

    def section(self, name: str, **values) -> None:
        self.lines += ["", f"[{name}]"] + [f"{k}={v}" for k, v in values.items()]

    def var(self, name: str, title: str, dtype: int, access: str, default, mappable: bool = False) -> None:
        self.section(name, ParameterName=title, ObjectType="0x7", DataType=f"0x{dtype:04X}", AccessType=access,
                     DefaultValue=default, PDOMapping=int(mappable))


def _ascii(s: str, fallback: str) -> str:
    return s if s and s.isascii() else fallback


def device_eds(cmap: MapCan, bus: Bus, dev: Device, warn: Callable[[str], None] = lambda _m: None) -> str:
    lang = cmap.lang
    pdos = [f for f in dev.frames if f.type.startswith("pdo_")]
    maps = {f.name: m for f in pdos if (m := _mapping(f, warn)) is not None}
    pdos = [f for f in pdos if f.name in maps]
    tx = [f for f in pdos if f.type.startswith("pdo_tx")]
    rx = [f for f in pdos if f.type.startswith("pdo_rx")]
    heartbeat = next((f for f in dev.frames if f.type == "heartbeat"), None)
    granular = all(length % 8 == 0 and idx >= 0x1000 or idx == UNSIGNED8
                   for m in maps.values() for idx, _sub, length in m)
    date = cmap.document.date or _dt.date.today()
    title = _ascii(text(dev.title, lang), dev.name)

    w = _Writer()
    source = _ascii(text(cmap.document.title, lang), "map")
    w.lines.append(f"; EDS of {dev.name}, generated by mapcan {__version__} from {source}")
    w.section("FileInfo", FileName=f"{dev.name}.eds", FileVersion=1, FileRevision=0, EDSVersion="4.0",
              Description=title, CreationTime="12:00AM", CreationDate=date.strftime("%m-%d-%Y"),
              CreatedBy="mapcan", ModificationTime="12:00AM", ModificationDate=date.strftime("%m-%d-%Y"),
              ModifiedBy="mapcan")
    rates = {f"BaudRate_{r}": int(bus.bitrate == r * 1000) for r in BAUD_RATES}
    w.section("DeviceInfo", VendorName=_ascii(cmap.document.organization or "", ""), VendorNumber=0,
              ProductName=title, ProductNumber=0, RevisionNumber=0, OrderCode="", **rates,
              SimpleBootUpMaster=0, SimpleBootUpSlave=1, Granularity=8 if granular else 1,
              DynamicChannelsSupported=0, GroupMessaging=0, NrOfRXPDO=len(rx), NrOfTXPDO=len(tx),
              LSS_Supported=0)
    used = {idx for m in maps.values() for idx, _s, _l in m if idx < 0x1000}
    w.section("DummyUsage", **{f"Dummy{i:04X}": int(i in used) for i in range(1, 8)})
    w.section("Comments", Lines=0)

    # Mandatory objects
    w.section("MandatoryObjects", SupportedObjects=3, **{"1": "0x1000", "2": "0x1001", "3": "0x1018"})
    w.var("1000", "Device type", 0x0007, "ro", "0x00000000")
    w.var("1001", "Error register", 0x0005, "ro", 0)
    w.section("1018", ParameterName="Identity object", ObjectType="0x9", SubNumber=5)
    w.var("1018sub0", "Highest sub-index supported", 0x0005, "ro", 4)
    for sub, name in enumerate(("Vendor-ID", "Product code", "Revision number", "Serial number"), 1):
        w.var(f"1018sub{sub}", name, 0x0007, "ro", "0x00000000")

    # PDO parameters and the dictionary: the communication area first, then the profiles, then the manufacturer
    optional, manufacturer = [], []
    if heartbeat is not None:
        optional.append((0x1017, lambda: w.var("1017", "Producer heartbeat time", 0x0006, "rw",
                                                heartbeat.cycle_ms or 0)))
    for f in sorted(pdos, key=lambda f: (f.type.startswith("pdo_tx"), pdo_number(f))):
        n = pdo_number(f) - 1
        comm, mapping = (0x1800 + n, 0x1A00 + n) if f.type.startswith("pdo_tx") else (0x1400 + n, 0x1600 + n)
        optional.append((comm, lambda f=f, comm=comm: _pdo_comm(w, f, comm)))
        optional.append((mapping, lambda f=f, mapping=mapping: _pdo_map(w, f, mapping, maps[f.name])))
    objects: dict[int, list[tuple[Signal, Frame]]] = {}
    for f in pdos:
        for s in f.signals:
            if s.index is not None:
                objects.setdefault(s.index, []).append((s, f))
    for index, items in sorted(objects.items()):
        (manufacturer if index < 0x6000 else optional).append(
            (index, lambda index=index, items=items: _object(w, index, items, lang)))
    optional.sort(key=lambda o: o[0])

    w.section("OptionalObjects", SupportedObjects=len(optional),
              **{str(i): f"0x{idx:04X}" for i, (idx, _w) in enumerate(optional, 1)})
    for _idx, write in optional:
        write()
    w.section("ManufacturerObjects", SupportedObjects=len(manufacturer),
              **{str(i): f"0x{idx:04X}" for i, (idx, _w) in enumerate(manufacturer, 1)})
    for _idx, write in manufacturer:
        write()
    return "\n".join(w.lines).lstrip("\n") + "\n"


def _cob_id(f: Frame) -> str:
    fc = FUNCTION_CODES[f.type]
    return f"0x{f.id:X}" if f.id is not None else f"$NODEID+0x{fc.base:X}"


def _pdo_comm(w: _Writer, f: Frame, index: int) -> None:
    tx = f.type.startswith("pdo_tx")
    kind = "TPDO" if tx else "RPDO"
    timer = tx and f.cycle_ms is not None
    inhibit = tx and f.inhibit_ms is not None
    w.section(f"{index:04X}", ParameterName=f"{kind}{pdo_number(f)} communication parameter", ObjectType="0x9",
              SubNumber=3 + inhibit + timer)
    w.var(f"{index:04X}sub0", "Highest sub-index supported", 0x0005, "ro", 5 if timer else 3 if inhibit else 2)
    w.var(f"{index:04X}sub1", f"COB-ID used by {kind}{pdo_number(f)}", 0x0007, "rw", _cob_id(f))
    w.var(f"{index:04X}sub2", "Transmission type", 0x0005, "rw", 254)
    if inhibit:
        w.var(f"{index:04X}sub3", "Inhibit time", 0x0006, "rw", round(f.inhibit_ms * 10))
    if timer:
        w.var(f"{index:04X}sub5", "Event timer", 0x0006, "rw", f.cycle_ms)


def _pdo_map(w: _Writer, f: Frame, index: int, mapping: list[tuple[int, int, int]]) -> None:
    kind = "TPDO" if f.type.startswith("pdo_tx") else "RPDO"
    w.section(f"{index:04X}", ParameterName=f"{kind}{pdo_number(f)} mapping parameter", ObjectType="0x9",
              SubNumber=len(mapping) + 1)
    w.var(f"{index:04X}sub0", "Number of mapped objects", 0x0005, "rw", len(mapping))
    for i, (idx, sub, length) in enumerate(mapping, 1):
        w.var(f"{index:04X}sub{i:X}", f"Mapped object {i}", 0x0007, "rw", f"0x{idx:04X}{sub:02X}{length:02X}")


def _object(w: _Writer, index: int, items: list[tuple[Signal, Frame]], lang: str) -> None:
    def entry(name: str, s: Signal, f: Frame) -> None:
        access = "ro" if f.type.startswith("pdo_tx") else "rww"
        init = s.initial_raw
        default = (init if s.is_float else int(init)) if init is not None else 0
        w.var(name, _ascii(text(s.title, lang), s.name), data_type(s), access, default, mappable=True)

    if len(items) == 1 and (items[0][0].subindex or 0) == 0:
        entry(f"{index:04X}", *items[0])
        return
    subs = sorted(items, key=lambda it: it[0].subindex or 0)
    top = max(s.subindex or 0 for s, _f in subs)
    w.section(f"{index:04X}", ParameterName=f"Object 0x{index:04X}", ObjectType="0x9", SubNumber=len(subs) + 1)
    w.var(f"{index:04X}sub0", "Highest sub-index supported", 0x0005, "ro", top)
    for s, f in subs:
        entry(f"{index:04X}sub{s.subindex or 0:X}", s, f)


def export_eds(cmap: MapCan, out: str | Path, bus_name: str | None = None,
               warn: Callable[[str], None] = lambda _m: None) -> list[Path]:
    """An EDS file for each device of the CANopen buses (or only of the bus ``bus_name``) in the folder ``out``."""
    out = Path(out)
    written = []
    for bus in cmap.buses:
        if bus.protocol != "canopen" or bus_name not in (None, bus.name):
            continue
        for dev in bus.devices:
            path = out / f"{dev.name}.eds"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(device_eds(cmap, bus, dev, warn), encoding="ascii", errors="replace", newline="\r\n")
            written.append(path)
    return written
