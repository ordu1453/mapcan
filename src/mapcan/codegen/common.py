def code_text(lang: str) -> dict[str, str]:
    return CODE_TEXT.get(lang, CODE_TEXT["en"])


def is_byte_array(s: Signal) -> bool:
    """A byte-aligned signal with encoding bytes or string is represented as an array (of chars for a string)."""
    return s.encoding in ("bytes", "string") and s.start_bit % 8 == 0 and s.bit_length % 8 == 0 \
        and s.byte_order == "little_endian"


def storage_bits(s: Signal) -> int:
    for n in (8, 16, 32, 64):
        if s.bit_length <= n:
            return n
    return 64


def frames_with_layout(bus: Bus) -> list[Frame]:
    return [f for f in bus.all_frames() if f.can_id is not None]


def selector_of(frame: Frame) -> Signal | None:
    return next((s for s in frame.layout if s.multiplexer), None)


def physical(s: Signal) -> bool:
    return s.factor != 1 or s.offset != 0 or s.encoding == "scaled"


def num(x: float) -> str:
    """float literal for C/Python without loss of precision."""
    r = repr(float(x))
    return r
