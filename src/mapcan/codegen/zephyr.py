def fits_can_frame(f: Frame) -> bool:
    """The frame is one struct can_frame: up to 8 bytes, up to 64 on CAN FD (not a transport-protocol PGN)."""
    return f.length <= (64 if f.bus.fd else 8)


class ZephyrGen:
    def __init__(self, g: CGen):
        self.g = g
        self.T = ZEPHYR_TEXT.get(g.lang, ZEPHYR_TEXT["en"])
        self.frames = [f for f in g.frames() if fits_can_frame(f)]
        self.device = g if isinstance(g, DeviceGen) else None

    def _flags(self, f: Frame) -> str:
        flags = [x for x, on in (("CAN_FRAME_IDE", f.extended), ("CAN_FRAME_FDF", f.bus.fd),
                                 ("CAN_FRAME_BRS", f.bit_rate_switch)) if on]
        return f"(uint8_t)({' | '.join(flags)})" if flags else "0u"

    def _fd_guard(self, f: Frame, body: list[str]) -> list[str]:
        return ["#ifdef CONFIG_CAN_FD_MODE", *body, "#endif"] if f.length > 8 else body

    # ------------------------------------------------------------------ #

    def header(self) -> str:
        g, base = self.g, self.g.base
        guard = f"{base.upper()}_ZEPHYR_H"
        out = [self.T["header"].format(base=base), f"#ifndef {guard}", f"#define {guard}", "",
               "#include <zephyr/kernel.h>", "#include <zephyr/drivers/can.h>", "", f'#include "{base}.h"', "",
               "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
        if any(f.length > 8 for f in self.frames):
            out += [f"/* {self.T['fd_only']} */", ""]
        for f in self.frames:
            t = g.p(g.frame_name(f))
            decls = []
            if g.packs(f):
                decls += [f"/* {self.T['to_frame']} */",
                          f"int {t}_to_can_frame(const {t}_t *msg, struct can_frame *frame);"]
            if g.unpacks(f):
                decls += [f"/* {self.T['from_frame']} */",
                          f"int {t}_from_can_frame({t}_t *msg, const struct can_frame *frame);"]
            out += self._fd_guard(f, decls)
        if self.device is not None:
            out += [""] + self._device_decls()
        out += ["", "#ifdef __cplusplus", "}", "#endif", "", f"#endif /* {guard} */", ""]
        return "\n".join(out)

    def source(self) -> str:
        base = self.g.base
        out = [self.T["source"].format(base=base), "#include <errno.h>", "#include <string.h>", "",
               f'#include "{base}_zephyr.h"', ""]
        for f in self.frames:
            out += self._fd_guard(f, self._frame_impl(f)) + [""]
        if self.device is not None:
            out += self._device_impl()
        return "\n".join(out)

    def _frame_impl(self, f: Frame) -> list[str]:
        g = self.g
        F = g.frame_name(f)
        t = g.p(F)
        out = []
        if g.packs(f):
            out += [f"int {t}_to_can_frame(const {t}_t *msg, struct can_frame *frame)", "{", "    int rc = -1;",
                    "    if ((msg != NULL) && (frame != NULL)) {",
                    "        (void)memset(frame, 0, sizeof(*frame));",
                    f"        rc = {t}_pack(frame->data, sizeof(frame->data), msg);",
                    "        if (rc >= 0) {",
                    f"            frame->id = {g.P(F, 'ID')};",
                    f"            frame->dlc = can_bytes_to_dlc((uint8_t){g.P(F, 'LENGTH')});",
                    f"            frame->flags = {self._flags(f)};",
                    "        }", "    }", "    return rc;", "}"]
        if g.unpacks(f):
            ide = "!= 0u" if f.extended else "== 0u"
            out += [f"int {t}_from_can_frame({t}_t *msg, const struct can_frame *frame)", "{", "    int rc = -1;",
                    f"    if ((msg != NULL) && (frame != NULL) && (frame->id == {g.P(F, 'ID')})",
                    f"        && ((frame->flags & CAN_FRAME_IDE) {ide}) && ((frame->flags & CAN_FRAME_RTR) == 0u)) {{",
                    f"        rc = {t}_unpack(msg, frame->data, can_dlc_to_bytes(frame->dlc));",
                    "    }", "    return rc;", "}"]
        return out

    # ------------------------------------------------------------------ #

    def _rx(self) -> list[Frame]:
        return [f for f in self.device.rx if fits_can_frame(f)]

    def _cyclic(self) -> list[Frame]:
        return [f for f in self.device.tx if fits_can_frame(f) and f.cycle_ms]

    def _device_decls(self) -> list[str]:
        g = self.device
        D = g.D
        out = []
        rx = self._rx()
        if rx:
            out += [f"#define {g.P(D, 'ZEPHYR_RX_FILTER_COUNT')} {len(rx)}u", f"/* {self.T['filters']} */",
                    f"extern const struct can_filter {g.p(D, 'zephyr_rx_filters')}"
                    f"[{g.P(D, 'ZEPHYR_RX_FILTER_COUNT')}];",
                    f"/* {self.T['add_filters']} */",
                    f"int {g.p(D, 'zephyr_add_rx_filters')}(const struct device *can, struct k_msgq *msgq);",
                    f"/* {self.T['dispatch']} */",
                    f"int {g.p(D, 'zephyr_dispatch')}({g.p(D, 'rx')}_t *rx, const struct can_frame *frame);"]
        if g.tx:
            tx_t, frame_t = f"{g.p(D, 'tx')}_t", f"{g.p(D, 'tx_frame')}_t"
            out += [f"/* {self.T['send']} */",
                    f"int {g.p(D, 'zephyr_send')}(const struct device *can, const {tx_t} *tx, {frame_t} frame);"]
            if self._cyclic():
                out += [f"/* {self.T['hook']} */",
                        f"typedef void (*{g.p(D, 'zephyr_tx_hook')}_t)({frame_t} frame, {tx_t} *tx, void *user_data);",
                        f"/* {self.T['tx_start']} */",
                        f"int {g.p(D, 'zephyr_tx_start')}(const struct device *can, {tx_t} *tx, "
                        f"{g.p(D, 'zephyr_tx_hook')}_t hook, void *user_data);",
                        f"/* {self.T['tx_stop']} */",
                        f"void {g.p(D, 'zephyr_tx_stop')}(void);"]
        return out

    def _device_impl(self) -> list[str]:
        g = self.device
        D = g.D
        out = []
        rx = self._rx()
        if rx:
            count = g.P(D, "ZEPHYR_RX_FILTER_COUNT")
            out.append(f"const struct can_filter {g.p(D, 'zephyr_rx_filters')}[{count}] = {{")
            for f in rx:
                mask, flags = ("CAN_EXT_ID_MASK", "CAN_FILTER_IDE") if f.extended else ("CAN_STD_ID_MASK", "0u")
                out.append(f"    {{.id = {g.P(g.frame_name(f), 'ID')}, .mask = {mask}, .flags = {flags}}},")
            out += ["};", "",
                    f"int {g.p(D, 'zephyr_add_rx_filters')}(const struct device *can, struct k_msgq *msgq)", "{",
                    "    int rc = 0;",
                    f"    for (size_t i = 0u; (i < {g.P(D, 'ZEPHYR_RX_FILTER_COUNT')}) && (rc >= 0); i++) {{",
                    f"        rc = can_add_rx_filter_msgq(can, msgq, &{g.p(D, 'zephyr_rx_filters')}[i]);",
                    "    }", "    return (rc < 0) ? rc : 0;", "}", "",
                    f"int {g.p(D, 'zephyr_dispatch')}({g.p(D, 'rx')}_t *rx, const struct can_frame *frame)", "{",
                    "    int rc = -1;",
                    "    if ((frame != NULL) && ((frame->flags & CAN_FRAME_RTR) == 0u)) {",
                    f"        rc = {g.p(D, 'rx_dispatch')}(rx, k_uptime_get_32(), frame->id, "
                    "(frame->flags & CAN_FRAME_IDE) != 0u, frame->data,",
                    "                    can_dlc_to_bytes(frame->dlc));", "    }", "    return rc;", "}", ""]
        if not g.tx:
            return out
        tx_t, frame_t = f"{g.p(D, 'tx')}_t", f"{g.p(D, 'tx_frame')}_t"
        out += [f"int {g.p(D, 'zephyr_send')}(const struct device *can, const {tx_t} *tx, {frame_t} frame)", "{",
                "    struct can_frame f;", "    int rc = -EINVAL;", "    if (tx != NULL) {", "        switch (frame) {"]
        for f in g.tx:
            if not fits_can_frame(f):
                continue
            F = g.frame_name(f)
            body = [f"        case {g.P(D, 'TX', F)}:",
                    f"            rc = ({g.p(F)}_to_can_frame(&tx->{F}, &f) >= 0) ? 0 : -EINVAL;",
                    "            break;"]
            out += self._fd_guard(f, body)
        out += ["        default:", "            break;", "        }", "    }",
                "    if (rc == 0) {", "        rc = can_send(can, &f, K_NO_WAIT, NULL, NULL);", "    }",
                "    return rc;", "}", ""]
        cyclic = self._cyclic()
        if not cyclic:
            return out
        n = len(cyclic)
        hook_t = f"{g.p(D, 'zephyr_tx_hook')}_t"
        st = g.p(D, "zephyr_tx")
        out += ["/* The state of the cyclic transmission: one work item per cyclic frame */",
                "static struct {", "    const struct device *can;", f"    {tx_t} *tx;", f"    {hook_t} hook;",
                "    void *user_data;", f"    struct k_work_delayable work[{n}];", f"}} {st};", "",
                f"static const {frame_t} {st}_frames[{n}] = {{"]
        out += [f"    {g.P(D, 'TX', g.frame_name(f))}," for f in cyclic]
        out += ["};", "",
                f"static void {st}_work(struct k_work *work)", "{",
                "    struct k_work_delayable *dwork = k_work_delayable_from_work(work);",
                f"    size_t i = (size_t)(dwork - &{st}.work[0]);",
                f"    {frame_t} frame = {st}_frames[i];",
                f"    if ({st}.hook != NULL) {{", f"        {st}.hook(frame, {st}.tx, {st}.user_data);", "    }",
                f"    (void){g.p(D, 'zephyr_send')}({st}.can, {st}.tx, frame);",
                f"    (void)k_work_reschedule(dwork, K_MSEC({g.p(D, 'tx_schedule')}[frame].cycle_ms));", "}", "",
                f"int {g.p(D, 'zephyr_tx_start')}(const struct device *can, {tx_t} *tx, {hook_t} hook, "
                "void *user_data)", "{",
                "    if ((can == NULL) || (tx == NULL)) {", "        return -EINVAL;", "    }",
                f"    {st}.can = can;", f"    {st}.tx = tx;", f"    {st}.hook = hook;",
                f"    {st}.user_data = user_data;",
                f"    for (size_t i = 0u; i < {n}u; i++) {{",
                f"        k_work_init_delayable(&{st}.work[i], {st}_work);",
                f"        (void)k_work_schedule(&{st}.work[i], K_NO_WAIT);", "    }", "    return 0;", "}", "",
                f"void {g.p(D, 'zephyr_tx_stop')}(void)", "{",
                f"    for (size_t i = 0u; i < {n}u; i++) {{",
                f"        (void)k_work_cancel_delayable(&{st}.work[i]);", "    }", "}", ""]
        return out


def write_zephyr(g: CGen, out: Path) -> list[Path]:
    """<base>_zephyr.h and <base>_zephyr.c next to the files of ``g``."""
    z = ZephyrGen(g)
    h, c = out / f"{g.base}_zephyr.h", out / f"{g.base}_zephyr.c"
    h.write_text(z.header(), encoding="utf-8")
    c.write_text(z.source(), encoding="utf-8")
    return [h, c]
