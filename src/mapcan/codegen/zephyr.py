"""Zephyr RTOS adapter of the generated C code (``mapcan gen c --target zephyr``).

A thin layer over the driver-independent code: ``<base>_zephyr.h`` / ``<base>_zephyr.c`` convert messages to
and from ``struct can_frame`` of ``<zephyr/drivers/can.h>`` (ID, IDE/FDF/BRS flags, DLC), and for a device
(``--device``) install its acceptance filters, dispatch received frames, send its frames and run its TX
schedule on ``k_work_delayable`` items.
"""

